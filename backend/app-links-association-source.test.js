'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const os=require('node:os');
const path=require('node:path');
const {associationPayload,writeAssociations}=require('../scripts/build-app-links-associations.cjs');
const root=fs.mkdtempSync(path.join(os.tmpdir(),'ar-app-links-'));
const fakeTeam='ABCDEFGHIJ',fakeSha=Array(32).fill('AB').join(':');
const well=path.join(root,'.well-known');
const applePath=path.join(well,'apple-app-site-association');
const androidPath=path.join(well,'assetlinks.json');
try{
  assert.equal(writeAssociations(root,{}).generated,false,'unverified links never published');
  assert.equal(fs.existsSync(well),false);
  assert.throws(()=>associationPayload('BAD',''),/Verified Apple Team/);
  assert.throws(()=>associationPayload('','00:11'),/Verified Google Play/);
  assert.throws(()=>writeAssociations(root,{AR_APPLE_TEAM_ID:fakeTeam,AR_ANDROID_PLAY_SHA256:'00:11'}),/Verified Google Play/);
  assert.equal(fs.existsSync(well),false,'invalid identity must produce zero files');
  const appleOnly=writeAssociations(root,{AR_APPLE_TEAM_ID:fakeTeam});
  assert.deepEqual(appleOnly,{generated:true,appleGenerated:true,androidGenerated:false});
  assert.equal(fs.existsSync(applePath),true);
  assert.equal(fs.existsSync(androidPath),false,'never guess missing Google Play fingerprint');
  const a=JSON.parse(fs.readFileSync(applePath,'utf8'));
  assert.deepEqual(a.applinks.details[0].appIDs,[fakeTeam+'.com.americanrider.app']);
  assert.deepEqual(a.applinks.details[0].components,[{'/':'/join'},{'/':'/join/*'}]);
  fs.rmSync(well,{recursive:true});
  const androidOnly=writeAssociations(root,{AR_ANDROID_PLAY_SHA256:fakeSha});
  assert.deepEqual(androidOnly,{generated:true,appleGenerated:false,androidGenerated:true});
  assert.equal(fs.existsSync(applePath),false,'never guess Apple Team ID');
  assert.equal(fs.existsSync(androidPath),true);
  fs.rmSync(well,{recursive:true});
  const both=writeAssociations(root,{AR_APPLE_TEAM_ID:fakeTeam,AR_ANDROID_PLAY_SHA256:fakeSha});
  assert.deepEqual(both,{generated:true,appleGenerated:true,androidGenerated:true});
  const g=JSON.parse(fs.readFileSync(androidPath,'utf8'));
  assert.equal(g[0].target.package_name,'com.americanrider.app');
  assert.deepEqual(g[0].target.sha256_cert_fingerprints,[fakeSha]);
  console.log('PASS Apple and Android verified domain associations independently; neither blocks the other');
}finally{fs.rmSync(root,{recursive:true,force:true});}
