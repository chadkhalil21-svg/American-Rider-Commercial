'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const file = fs.readFileSync('.github/workflows/build-certified-android-play.yml', 'utf8');
const app = JSON.parse(fs.readFileSync('app.json', 'utf8')).expo;
const eas = JSON.parse(fs.readFileSync('eas.json', 'utf8'));
assert.match(file, /workflow_dispatch:/);
assert.match(file, /certified_sha:/);
assert.match(file, /\^\[0-9a-f\]\{40\}\$/);
assert.match(file, /git rev-parse FETCH_HEAD/);
assert.match(file, /release\/current/);
assert.match(file, /--platform android --profile production --non-interactive --wait --json/);
assert.match(file, /Not submitted to or approved by Google Play/);
assert.doesNotMatch(file, /eas-cli@latest submit|auto-submit|--platform all/);
assert.equal(app.android.package, 'com.americanrider.app');
assert.ok(eas.build.production, 'production EAS build configuration exists');
assert.notEqual(eas.build.production.distribution, 'internal');
assert.notEqual(eas.build.production.android?.buildType, 'apk');
console.log('Android exact-release production build workflow verified (build-only; no Play submission).');
