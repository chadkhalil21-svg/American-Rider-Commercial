'use strict';
const assert = require('node:assert/strict');
const { spawnSync } = require('node:child_process');
const fs = require('node:fs');
const path = require('node:path');
const script = path.resolve(__dirname, '../infra/cloud-run/bootstrap-github-identity.sh');
const workflow = fs.readFileSync(path.resolve(__dirname, '../.github/workflows/cloud-run-staging.yml'), 'utf8');
const content = fs.readFileSync(script, 'utf8');
const syntax = spawnSync('bash', ['-n', script], { encoding: 'utf8', timeout: 5000 });
assert.equal(syntax.status, 0, syntax.stderr);
for (const mode of ['staging', 'production']) {
  const result = spawnSync('bash', [script, mode], { encoding: 'utf8', timeout: 5000 });
  assert.equal(result.status, 0, result.stderr);
  assert.match(result.stdout, /DRY RUN ONLY/);
  assert.match(result.stdout, /Excludes: Cloud Run services, payments/);
}
const invalid = spawnSync('bash', [script, 'invalid'], { encoding: 'utf8', timeout: 5000 });
assert.notEqual(invalid.status, 0);
const prodGuard = spawnSync('bash', [script, 'production', '--apply'], { encoding: 'utf8', timeout: 5000 });
assert.notEqual(prodGuard.status, 0, 'production has a separate explicit approval');
assert.match(prodGuard.stderr, /explicit AR_APPROVE_PRODUCTION_IDENTITY/);
assert.match(content, /gcloud iam workload-identity-pools providers create-oidc/);
assert.match(content, /ACTUAL_CONDITION/);
assert.match(content, /Existing GitHub provider condition differs/);
assert.match(content, /roles\/iam\.workloadIdentityUser/);
assert.match(content, /roles\/iam\.serviceAccountUser/);
assert.match(content, /roles\/run\.sourceDeveloper/);
assert.match(content, /roles\/serviceusage\.serviceUsageConsumer/);
assert.match(content, /roles\/run\.builder/);
assert.match(content, /CANDIDATE=/);
assert.match(content, /gcloud iam service-accounts describe "\$CANDIDATE"/);
assert.match(content, /gcloud iam service-accounts add-iam-policy-binding "\$BUILD_SA"/);
assert.match(content, /roles\/iam\.serviceAccountUser --quiet/);
assert.match(content, /No verified build service account/);
assert.doesNotMatch(content, /gcloud run deploy|gcloud run services update/);
assert.doesNotMatch(content, /service-accounts keys create/);
assert.match(workflow, /id-token: write/);
assert.match(workflow, /projects\/926320586690\/locations\/global\/workloadIdentityPools\/github-staging\/providers\/github/);
assert.match(workflow, /ar-staging-deployer@american-rider-staging-2026/);
assert.match(workflow, /ar-staging-runtime@american-rider-staging-2026/);
assert.doesNotMatch(workflow, /secrets\.STAGING_GCP_|vars\.STAGING_GCP_/);
assert.match(workflow, /--no-allow-unauthenticated/);
assert.match(workflow, /--min-instances=0/);
console.log('PASS: reusable no-deploy Cloud Run IAM bootstrap and no duplicate GitHub identifier secrets');
