'use strict';
// Synthetic source contract. No Stripe live charges, payouts, or user updates.
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const root=path.resolve(__dirname,'..');
const account=require('./operatorfees');
const q0=account.accountFeeQuote(0,false,'US');
const q1=account.accountFeeQuote(0,true,'US');
const q100=account.accountFeeQuote(100,true,'US');
assert.equal(q0.costCents,0,'no payout, no account fee');
assert.equal(q1.costCents,200,'first monthly bank payout triggers fee');
assert.equal(q100.costCents,200,'no 20-Travel volume waiver');
assert.equal(q1.totalCents,237,'card-cost gross up is separate');
assert.equal(account.FEE_CONSENT_VERSION,'connect-fees-2026-10');
const code=fs.readFileSync(path.join(__dirname,'operatorfees.js'),'utf8');
const server=fs.readFileSync(path.join(__dirname,'server.js'),'utf8');
const screen=fs.readFileSync(path.join(root,'app/operator/payouts.tsx'),'utf8');
const client=fs.readFileSync(path.join(root,'src/backend/connect.ts'),'utf8');
assert.match(code,/consent\.acceptedAt > rec\.lastPayoutAt/,'no backbilling a payout before agreement');
assert.match(code,/feeStatus:'consent_required'/,'without consent, no unapproved bank charge');
assert.match(server,/app\.post\('\/connect\/fee-consent'/,'explicit, authenticated consent endpoint exists');
assert.match(server,/req\.body\?\.agreeFeePolicy!==true/,'no inferred agreement');
assert.match(server,/tx\.set\(ref,\{stripeFeeConsent:consent\}/,'consent recorded on server');
assert.match(server,/error:'Review and agree/,'new payout onboarding blocked until agreement');
assert.match(client,/acceptConnectFees/);
assert.match(screen,/feeConsentAccepted/);
assert.match(screen,/operator\.feeConsentAccept/);
console.log('PASS: separate Connect $2 recovery requires payout and prior express agreement; no 20-Travel waiver; UI review; zero live charges');
