'use strict';
const assert=require('node:assert/strict');
const {DEFAULT,PRICES,evaluate}=require('./commercial-economics');
const noTrips=evaluate({travelsPerDay:0,operatorsOnDutyDaily:0,assumedFixedMonthlyUsd:500});
assert.equal(noTrips.travelsMonthly,0);
assert.equal(noTrips.modeledOperatingResultUsd,-507,'the existing $7 Render API remains a named expense even at zero Travels');
const v=evaluate();
assert.equal(v.travelsMonthly,1500);
assert.equal(v.domesticModeledContributionUsd,1.14);
assert.equal(v.internationalModeledContributionUsd,0.84);
assert.equal(v.transactionRoomBeforeActualOverheadUsd,1.38); // 95% * 1.39 + 5% * 1.09 = 1.375, rounding is half-up
assert.equal(v.presenceWritesPerDay,9600);
assert.equal(v.firestoreWritesPerDay,12100);
assert.equal(v.firestoreReadsPerDay,7500);
assert.equal(v.freeTierAssumed,true);
assert.equal(v.cloudRunCostUsd,0);
assert.equal(v.firestoreCostUsd,0);
assert.equal(v.legacyRenderApiUsd,7);
assert.equal(v.cloudSchedulerUsd,0,'one scheduled job is within the three-job free tier');
assert.equal(v.knownServiceCostsUsd,7,'only the explicitly identified legacy hosting fee is in this low-usage scenario');
assert.equal(v.r2Usd,0,'Cloudflare R2 fits within its own free storage and request quotas');
assert.equal(evaluate({r2StorageGibMonths:110}).r2Usd,1.5);
assert.equal(evaluate({r2ClassARequestsMonthly:2000000,r2ClassBRequestsMonthly:20000000}).r2Usd,8.1);
const unknownHere=evaluate({hereAutosuggestRequestsMonthly:10000,hereTollRequestsMonthly:10});
assert.equal(unknownHere.hereUsageUnpriced,true,'no fictional HERE cost without an account-specific per-request rate');
assert.equal(unknownHere.hereAutosuggestUsd,null);
assert.equal(unknownHere.hereTollUsd,null);
const pricedHere=evaluate({hereAutosuggestRequestsMonthly:10000,hereAutosuggestUsdPer1000:1,hereTollRequestsMonthly:500,hereTollUsdPer1000:4});
assert.equal(pricedHere.hereUsageUnpriced,false);
assert.equal(pricedHere.hereAutosuggestUsd,10);
assert.equal(pricedHere.hereTollUsd,2);
assert.equal(pricedHere.knownServiceCostsUsd,19);
assert.throws(()=>evaluate({r2StorageGibMonths:-1}),/nonnegative/);
assert.throws(()=>evaluate({hereTollUsdPer1000:-1}),/nonnegative/);
assert.equal(evaluate({cloudSchedulerJobs:4}).cloudSchedulerUsd,0.1);
assert.equal(evaluate({legacyRenderApiMonthlyUsd:0}).legacyRenderApiUsd,0,'can be removed after documented retirement');
assert(v.modeledOperatingResultUsd>0,'default model includes no hypothetical monthly company expenses');
const demand=evaluate({travelsPerDay:100,internationalShare:0,assumedFixedMonthlyUsd:2000});
assert(demand.modeledOperatingResultUsd>0);
assert(evaluate({travelsPerDay:100,internationalShare:1,assumedFixedMonthlyUsd:2000}).modeledOperatingResultUsd<
  demand.modeledOperatingResultUsd,'foreign-card exposure must reduce returns');
const fee=evaluate({travelsPerDay:50,activePayoutAccountsMonthly:20});
assert.equal(fee.accountFeeUsd,40,'payout-active Connect accounts have real provider costs');
assert.equal(fee.operatorRecoveredAccountFeeUsd,0,'no money assumed collected without proof');
assert.equal(evaluate({travelsPerDay:50,activePayoutAccountsMonthly:20,recoveredAccountFeeFraction:1}).operatorRecoveredAccountFeeUsd,40);
assert.equal(evaluate({monthlyResendEmailCount:150,peakDailyResendEmailCount:101}).resendUsd,20,'Resend daily free limit matters');
assert.equal(evaluate({monthlyResendEmailCount:4000,peakDailyResendEmailCount:50}).resendUsd,20);
assert.equal(evaluate({monthlyResendEmailCount:0,peakDailyResendEmailCount:0}).resendUsd,0);
assert.equal(v.assumedFixedMonthlyUsd,0,'do not invent flat operating expenses');
assert.match(v.economicsStatus,/NOT NET PROFIT/);
const busy=evaluate({travelsPerDay:1000,operatorsOnDutyDaily:500});
assert(busy.firestoreCostUsd>0&&busy.cloudRunCostUsd>0);
assert(busy.presenceWritesPerDay===160000);
assert(busy.firestoreWritesPerDay>20000);
const allCharge=evaluate({travelsPerDay:100,assumedFixedMonthlyUsd:0,useFreeTiers:false});
const someFree=evaluate({travelsPerDay:100,assumedFixedMonthlyUsd:0});
assert(allCharge.cloudRunCostUsd>someFree.cloudRunCostUsd);
assert(allCharge.firestoreCostUsd>someFree.firestoreCostUsd);
assert(evaluate({travelsPerDay:100,assumedFixedMonthlyUsd:20000}).modeledOperatingResultUsd<0);
assert.throws(()=>evaluate({travelsPerDay:-1}),/nonnegative/);
assert.throws(()=>evaluate({useFreeTiers:'yes'}),/boolean/);
assert.throws(()=>evaluate({internationalShare:1.5}),/must not exceed/);
assert.throws(()=>evaluate({somethingMadeUp:1}),/unsupported/);
console.log('PASS synthetic economics: source-faithful card fees, daily free tiers, active Operator GPS writes, profitability sensitivity and unknown overhead');
