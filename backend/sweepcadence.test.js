'use strict';
const assert=require('node:assert/strict');
const {PERIOD_MS,createSweepCadence,quotaError,createQuotaBackoff}=require('./sweepcadence');
(async()=>{
  assert.equal(PERIOD_MS.screening,6*60*60_000);
  assert.equal(PERIOD_MS.insuranceMonitoring,30*60_000);
  assert.equal(PERIOD_MS.founderMarketIntent,10*60_000);
  assert.equal(PERIOD_MS.operatorFees,6*60*60_000);
  const clock=createSweepCadence();let calls=0;const f=async()=>{calls++;return {ok:true};};
  const now=100_000_000;
  assert.equal((await clock.run('screening',f,now)).ok,true);
  assert.equal((await clock.run('screening',f,now+60_000)).skipped,'cadence');
  assert.equal(calls,1);
  assert.equal((await clock.run('screening',f,now+5*60*60_000)).skipped,'cadence',
    'screening renewal sweep is reminders only; real-time acceptance independently checks expiry');
  assert.equal((await clock.run('screening',f,now+6*60*60_000)).ok,true);
  assert.equal(calls,2);
  assert.equal((await clock.run('founderMarketIntent',f,now)).ok,true);
  assert.equal((await clock.run('founderMarketIntent',f,now+9*60_000)).skipped,'cadence');
  assert.equal((await clock.run('founderMarketIntent',f,now+10*60_000)).ok,true);
  assert.equal((await clock.run('insuranceMonitoring',f,now+60_000)).ok,true,'different jobs have separate cadence');
  assert.equal((await clock.run('insuranceMonitoring',f,now+2*60_000)).skipped,'cadence');
  assert.equal((await clock.run('accountDeletion',f,now+60_000)).ok,true);
  assert.equal((await clock.run('accountDeletion',f,now+61*60_000)).ok,true);
  assert.equal((await clock.run('operatorFees',f,now+60_000)).ok,true);
  assert.equal((await clock.run('operatorFees',f,now+5*60*60_000)).skipped,'cadence');
  assert.equal((await clock.run('operatorFees',f,now+6*60*60_000+60_000)).ok,true);
  assert.equal((await clock.run('marketReference',f,now+60_000)).ok,true);
  assert.equal((await clock.run('marketReference',f,now+60*60_000+60_000)).skipped,'cadence');
  assert.equal((await clock.run('marketReference',f,now+24*60*60_000+60_000)).ok,true);
  assert.equal(clock.due('familyAgeOut',now),true);
  assert.equal(clock.due('familyAgeOut',now-60_000),true,'time moved back: allow recovery');
  assert.rejects(async()=>clock.run('bogus',f,now));
  assert.equal(quotaError({reason:'8 RESOURCE_EXHAUSTED: Quota exceeded.'}),true);
  assert.equal(quotaError({message:'8 RESOURCE_EXHAUSTED'}),true);
  assert.equal(quotaError({code:'normal'}),false);
  const backoff=createQuotaBackoff();
  assert.equal(backoff.blocked(now),false);
  assert.equal(backoff.failure(now),now+5*60_000);
  assert.equal(backoff.blocked(now+60_000),true);
  assert.equal(backoff.remainingMs(now+60_000),4*60_000);
  assert.equal(backoff.blocked(now+5*60_000),false);
  assert.equal(backoff.failure(now+5*60_000),now+15*60_000);
  assert.equal(backoff.failure(now+15*60_000),now+25*60_000);
  assert.equal(backoff.failure(now+25*60_000),now+35*60_000);
  assert.equal(backoff.failure(now+35*60_000),now+45*60_000);
  backoff.clear();
  assert.equal(backoff.blocked(now+75*60_000),false);
  assert.equal(backoff.failure(now+75*60_000),now+80*60_000);
  console.log('PASS: due-only maintenance cadence and Firestore quota backpressure');
})().catch(e=>{console.error(e);process.exitCode=1});
